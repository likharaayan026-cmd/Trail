export function createDefaultUpgrades(): UpgradeLevels {
  return {
    engine: 1,
    tires: 1,
    suspension: 1,
    awd: 1,
    fuel: 1,
    grip: 1,
    brakes: 1,
    aero: 1,
  };
}

export function getUpgradeCost(vehicle: VehicleDef, key: UpgradeKey, currentLevel: number): number {
  const categoryFactor: Record<UpgradeKey, number> = {
    engine: 1.15,
    tires: 1.0,
    suspension: 1.05,
    awd: 1.2,
    fuel: 0.95,
    grip: 1.0,
    brakes: 0.9,
    aero: 1.1,
  };
  const base = vehicle.baseUpgradeCost * categoryFactor[key];
  return Math.round(base * Math.pow(1.42, currentLevel - 1) / 10) * 10;
}

export function computeEffectiveStats(vehicle: VehicleDef, upgrades: UpgradeLevels): VehicleStats {
  const b = vehicle.baseStats;
  const eng = upgrades.engine - 1;
  const tir = upgrades.tires - 1;
  const sus = upgrades.suspension - 1;
  const awd = upgrades.awd - 1;
  const fue = upgrades.fuel - 1;
  const grp = upgrades.grip - 1;
  const brk = upgrades.brakes - 1;
  const aer = upgrades.aero - 1;

  return {
    enginePower: b.enginePower * (1 + eng * 0.085),
    maxSpeed: b.maxSpeed * (1 + eng * 0.052 + aer * 0.015),
    mass: b.mass,
    wheelRadius: b.wheelRadius * (1 + tir * 0.02),
    wheelBase: b.wheelBase,
    suspensionStiffness: b.suspensionStiffness * (1 + sus * 0.055),
    suspensionDamping: b.suspensionDamping * (1 + sus * 0.075),
    suspensionTravel: b.suspensionTravel * (1 + sus * 0.05),
    awdRatio: Math.min(1.0, b.awdRatio + awd * 0.075),
    fuelCapacity: b.fuelCapacity * (1 + fue * 0.095),
    gripFactor: b.gripFactor * (1 + tir * 0.04 + grp * 0.065),
    brakeForce: b.brakeForce * (1 + brk * 0.09),
    airControl: b.airControl * (1 + brk * 0.04 + aer * 0.045),
    aeroDrag: Math.max(0.00035, b.aeroDrag * Math.pow(0.93, aer)),
    rollCageProtection: Math.min(0.85, b.rollCageProtection + sus * 0.015),
  };
}
